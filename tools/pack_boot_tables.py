"""Pack immutable generated lookup tables for one-time expansion before audio starts."""
from pathlib import Path
import re,struct
import lz4blk
PATTERN=re.compile(r'static const (u?int(?:8|16|32)_t) (\w+)(\[[^\]]*\](?:\[[^\]]*\])*)\s*=\s*\{([^;]+)\};')

def pack(gen):
    from pack_uac_fir import pack_uac_fir
    fir_ram=pack_uac_fir(gen)
    gen=Path(gen);entries=[];oracle=bytearray();total_raw=total_packed=0
    for filename in ['felucca_tables.h','felucca_font.h','felucca_drumkits.h','felucca_icons.h','felucca_fm6.h']:
        path=gen/filename;text=path.read_text()
        if 'BOOT_TABLES_PACKED' in text:raise ValueError('Regenerate raw headers before packing boot tables')
        def replace(m):
            nonlocal total_raw,total_packed
            typ,name,dims,body=m.groups()
            body=re.sub(r"/\*.*?\*/|//[^\n]*", "", body, flags=re.S)
            if re.search('[A-Za-z_]',re.sub('0[xX][0-9a-fA-F]+','',body)):return m[0]
            values=[int(x,0) for x in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+',body)]
            unit=int(re.search(r'\d+',typ)[0])//8;mask=(1<<(unit*8))-1
            raw=b''.join((v&mask).to_bytes(unit,'little') for v in values)
            if len(raw)<200:return m[0]
            candidates=[(lz4blk.compress(raw),0,unit,raw,0)]
            for order in range(1,5):
                if len(values)<=order:continue
                d=values
                for _ in range(order):d=[b-a for a,b in zip(d,d[1:])]
                prefix=raw[:order*unit]
                for width in {unit,1}:
                    if width==1 and unit>1 and not all(-128<=v<=127 for v in d):continue
                    encoded=prefix+b''.join((v&((1<<(width*8))-1)).to_bytes(width,'little') for v in d)
                    candidates.append((lz4blk.compress(encoded),order,width,encoded,0))
            for order in range(5):
                if len(values)<=order:continue
                d=values
                for _ in range(order):d=[b-a for a,b in zip(d,d[1:])]
                lo=min(d);bits=(max(d)-lo).bit_length() or 1
                if bits>31 or not -(1<<31)<=lo<(1<<31):continue
                packed=bytearray(raw[:order*unit]);packed.extend((lo&0xffffffff).to_bytes(4,'little'))
                acc=used=0
                for v in d:
                    acc|=(v-lo)<<used;used+=bits
                    while used>=8:packed.append(acc&255);acc>>=8;used-=8
                if used:packed.append(acc&255)
                candidates.append((bytes(packed),order,unit,bytes(packed),bits))
            blob,order,width,encoded,bits=min(candidates,key=lambda t:len(t[0]))
            assert bits or lz4blk.decompress(blob)==encoded
            if len(raw)-len(blob)<112:return m[0]
            # Guard the total early-boot RAM budget; never spill into the audio pool.
            if total_raw+len(raw)+fir_ram>24000:raise ValueError('Boot-table RAM budget exceeded')
            total_raw+=len(raw);total_packed+=len(blob);oracle.extend(raw)
            entries.append((name,len(values),unit,order,width,len(blob),bits))
            data=',\n'.join('    '+','.join(map(str,blob[i:i+24])) for i in range(0,len(blob),24))
            return f'''#if FELUCCA_BOOT_TABLES
static {typ} {name}{dims};
static const uint8_t BOOT_{name}[] = {{
{data}
}};
#else
{m[0]}
#endif'''
        text=PATTERN.sub(replace,text)
        path.write_text('/* BOOT_TABLES_PACKED: expanded into RAM before audio starts. */\n'+text)
    lines=['/* Generated by pack_boot_tables.py. */','#pragma once','#if FELUCCA_BOOT_TABLES','#include "boot_tables.c"','static const boot_table_t BOOT_TABLES[] = {']
    for name,n,unit,order,width,packed,bits in entries:
        if name.startswith('FONT_'):lines.append('#if !FELUCCA_BOOT_AUDIO_ONLY')
        lines.append(f'    {{{name}, BOOT_{name}, {packed}, {n}, {unit}, {order}, {width}, {bits}}},')
        if name.startswith('FONT_'):lines.append('#endif')
    lines+=['};','static int boot_tables_init(void)','{','    for (uint32_t i=0;i<sizeof BOOT_TABLES/sizeof BOOT_TABLES[0];i++)','        if (!boot_table_unpack(&BOOT_TABLES[i])) return 0;','#if !FELUCCA_BOOT_AUDIO_ONLY','    uac_fir_init();','#endif','    return 1;','}','#endif']
    (gen/'boot_tables_init.h').write_text('\n'.join(lines)+'\n')
    (gen/'boot_tables_oracle.bin').write_bytes(oracle)
    (gen/'boot_tables_report.txt').write_text('\n'.join(map(str,entries))+f'\nRAM {total_raw}; packed {total_packed}; gross saved {total_raw-total_packed}\n')
    print(f'boot tables: {len(entries)} tables, {total_raw} bytes RAM, {total_packed} bytes flash payload, {total_raw-total_packed} bytes gross saved')

if __name__=='__main__':
    import sys
    pack(sys.argv[1])
