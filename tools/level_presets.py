"""Measures every factory preset and writes firmware/src/preset_trim.h: a level trim per preset
(1/2 dB, the steps of LEVEL), so every sound comes out as loud as the others at the same LEVEL.
Loudness: ITU-R BS.1770 integrated (gated) over a phrase that fits the sound (tests/preset_level.c:
a bass line, held chords, comping or a melody).

  cc -O2 -Ibuild/gen -Ifirmware/src -Ifirmware/hal tests/preset_level.c -lm -o build/host/preset_level
  build/host/preset_level build/host/presets.wav build/host/presets.txt build/host/presets.raw
  tools/level_presets.py build/host/presets.raw build/host/presets.txt [ENGINE]
  (rebuild and run it again until nothing moves: the trims add to the ones in preset_trim.h)
  ENGINE: only that engine's presets are measured again (a new engine: the others keep their trims, so
  their golden renders do not move; SLOOP 2.4: FM6 = 9).
Needs numpy and scipy."""
import re
import sys
from pathlib import Path

FS, CTL = 44100, 32
SEG = (FS * 9 // 2) // CTL * CTL + (FS // 4) // CTL * CTL
OUT = Path(__file__).resolve().parent.parent / "firmware/src/preset_trim.h"
TARGET = -15.0                                 # LUFS (integrated), at the default LEVEL
ROLE = {0: 0.0, 1: -1.0, 2: 0.0, 3: 0.0, 4: 0.0}   # bass, chords held (pads, organs), comping, melody, one-key chords
SKIP = {"GM KIT"}                              # (the drum map on a synth track: as it is)


def lufs(x):
    import numpy as np
    from scipy.signal import lfilter
    b1 = [1.53512485958697, -2.69169618940638, 1.19839281085285]
    a1 = [1, -1.69065929318241, 0.73248077421585]
    b2, a2 = [1, -2, 1], [1, -1.99004745483398, 0.99007225036621]
    k = lfilter(b2, a2, lfilter(b1, a1, x)) ** 2
    w, h = int(0.4 * FS), int(0.1 * FS)
    bl = np.array([k[i:i + w].mean() for i in range(0, len(k) - w, h)])
    bl = bl[bl > 1e-7]
    if not len(bl):
        return None
    g = bl[10 * np.log10(bl) - 0.691 > -70]
    rel = 10 * np.log10(g.mean()) - 0.691 - 10
    g = g[10 * np.log10(g) - 0.691 > rel]
    return 10 * np.log10(g.mean()) - 0.691


def format_header(tab, names):
    """Keep preset indices/comments, omitting only unused zero tails."""
    if not tab or len(tab) != len(names):
        raise ValueError("trim tables need matching nonempty engine rows")
    pmax = len(tab[0])
    if not 0 < pmax <= 255 or any(len(row) != pmax for row in tab + names):
        raise ValueError("trim rows must share a uint8-sized preset capacity")
    offsets, counts, rows = [], [], []
    total = 0
    for e, (values, labels) in enumerate(zip(tab, names)):
        if any(not -128 <= value <= 127 for value in values):
            raise ValueError("trim values must fit int8")
        count = max((p + 1 for p in range(pmax) if labels[p] or values[p]), default=0)
        offsets.append(total)
        counts.append(count)
        total += count
        rows.append("    " + ", ".join(
            f"/* {e}.{p} {labels[p] or '-'} */ {values[p]}" for p in range(count)) + ("," if count else ""))
    if total > 65535:
        raise ValueError("trim offsets exceed uint16")
    lines = ["/* generated by tools/level_presets.py: the level trim of each factory preset, 1/2 dB */",
             "#pragma once", "#include <stdint.h>", f"#define PT_ENGINES {len(tab)}u", f"#define PT_MAX {pmax}u",
             "static const uint16_t PT_OFFSET[] = {" + ", ".join(map(str, offsets)) + "};",
             "static const uint8_t PT_COUNT[] = {" + ", ".join(map(str, counts)) + "};",
             "static const int8_t PRESET_TRIM[] = {"]
    lines += rows if total else ["    0"]
    lines += ["};", "static inline int16_t preset_trim_value(uint32_t e, uint32_t pi)",
              "{", "    return e < PT_ENGINES && pi < PT_COUNT[e] ? PRESET_TRIM[PT_OFFSET[e] + pi] : 0;", "}"]
    return "\n".join(lines) + "\n"


def main(raw, rep, only=None, new_only=False):
    import numpy as np
    rows = [l.split(None, 3) for l in Path(rep).read_text().splitlines()]
    d = np.fromfile(raw, np.int32).astype(float) / 32768.0
    old, old_rows = {}, []
    if OUT.exists():
        old_rows = re.findall(r"/\* (\d+)\.(\d+) (.*?) \*/ (-?\d+)", OUT.read_text())
        for e, _, name, v in old_rows:
            old[(int(e), name)] = int(v)              # (by name: presets may move in their table)
    seen = {int(r[0]) for r in rows}
    neng = max(seen | {int(e) for e, _, _, _ in old_rows}) + 1
    pmax = 32
    tab = [[0] * pmax for _ in range(neng)]
    names = [[""] * pmax for _ in range(neng)]
    # A normal no-SLICE render must retain the optional engine's calibrated row.
    for e, p, name, value in old_rows:
        if int(e) not in seen:
            tab[int(e)][int(p)] = int(value)
            names[int(e)][int(p)] = name
    for i, (e, p, role, name) in enumerate(rows):
        e, p, role = int(e), int(p), int(role)
        assert p < pmax, name
        names[e][p] = name
        L = lufs(d[i * SEG:(i + 1) * SEG])
        t = old.get((e, name), 0)
        if L is not None and name not in SKIP and (only is None or e == only) and (not new_only or (e, name) not in old):
            t += int(round((TARGET + ROLE[role] - L) * 2))
        tab[e][p] = max(-40, min(23, t))       # (LEVEL 104 + 23 = 127: the top of the table)
    OUT.write_text(format_header(tab, names))
    print(f"{len(rows)} presets levelled -> {OUT}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("raw")
    ap.add_argument("report")
    ap.add_argument("engine", nargs="?", type=int)
    ap.add_argument("--new-only", action="store_true", help="measure new names; preserve every existing trim")
    args = ap.parse_args()
    main(args.raw, args.report, args.engine, args.new_only)
