using System.Collections.Immutable;

namespace Sloop.SoundDesign;

public readonly record struct ModulationEdge(int Source, int Target);
public sealed record AlgorithmGraph(ImmutableArray<ModulationEdge> Edges,
    ImmutableArray<int> Carriers, ImmutableArray<int> FeedbackOperators)
{
    // Carriers occupy the bottom row. Every modulation edge goes down a row or more.
    public int Depth(int number) => Edges.Where(e => e.Source == number)
        .Select(e => Depth(e.Target) + 1).DefaultIfEmpty(0).Max();
}

public static class FirmwareAlgorithms
{
    // FM6_ALG in firmware/src/fm6_core.c, in render order OP6..OP1.
    static readonly byte[][] Routes = [
        [0xc1,0x11,0x11,0x14,0x01,0x14], [0x01,0x11,0x11,0x14,0xc1,0x14],
        [0xc1,0x11,0x14,0x01,0x11,0x14], [0xc1,0x11,0x94,0x01,0x11,0x14],
        [0xc1,0x14,0x01,0x14,0x01,0x14], [0xc1,0x94,0x01,0x14,0x01,0x14],
        [0xc1,0x11,0x05,0x14,0x01,0x14], [0x01,0x11,0xc5,0x14,0x01,0x14],
        [0x01,0x11,0x05,0x14,0xc1,0x14], [0x01,0x05,0x14,0xc1,0x11,0x14],
        [0xc1,0x05,0x14,0x01,0x11,0x14], [0x01,0x05,0x05,0x14,0xc1,0x14],
        [0xc1,0x05,0x05,0x14,0x01,0x14], [0xc1,0x05,0x11,0x14,0x01,0x14],
        [0x01,0x05,0x11,0x14,0xc1,0x14], [0xc1,0x11,0x02,0x25,0x05,0x14],
        [0x01,0x11,0x02,0x25,0xc5,0x14], [0x01,0x11,0x11,0xc5,0x05,0x14],
        [0xc1,0x14,0x14,0x01,0x11,0x14], [0x01,0x05,0x14,0xc1,0x14,0x14],
        [0x01,0x14,0x14,0xc1,0x14,0x14], [0xc1,0x14,0x14,0x14,0x01,0x14],
        [0xc1,0x14,0x14,0x01,0x14,0x04], [0xc1,0x14,0x14,0x14,0x04,0x04],
        [0xc1,0x14,0x14,0x04,0x04,0x04], [0xc1,0x05,0x14,0x01,0x14,0x04],
        [0x01,0x05,0x14,0xc1,0x14,0x04], [0x04,0xc1,0x11,0x14,0x01,0x14],
        [0xc1,0x14,0x01,0x14,0x04,0x04], [0x04,0xc1,0x11,0x14,0x04,0x04],
        [0xc1,0x14,0x04,0x04,0x04,0x04], [0xc4,0x04,0x04,0x04,0x04,0x04]
    ];

    public static AlgorithmGraph Get(int algorithm)
    {
        if (algorithm is < 1 or > 32) throw new ArgumentOutOfRangeException(nameof(algorithm));
        var buses = new HashSet<int>[] { [], [], [] };
        var edges = ImmutableArray.CreateBuilder<ModulationEdge>();
        var carriers = ImmutableArray.CreateBuilder<int>();
        var feedback = ImmutableArray.CreateBuilder<int>();
        for (int i = 0; i < 6; i++)
        {
            int number = 6 - i, flags = Routes[algorithm - 1][i];
            int input = (flags >> 4) & 3, output = flags & 3;
            if (input != 0)
                foreach (int source in buses[input].Order()) edges.Add(new(source, number));
            // The current renderer applies feedback only when both flags are set
            // and there is no input bus. FBOUT by itself does not close a loop.
            if ((input == 0 || buses[input].Count == 0) && (flags & 0xc0) == 0xc0)
                feedback.Add(number);
            if (output == 0) carriers.Add(number);
            if ((flags & 4) == 0) buses[output].Clear();
            buses[output].Add(number);
        }
        return new(edges.ToImmutable(), carriers.ToImmutable(), feedback.ToImmutable());
    }
}
